// Writes config.js, the browser's public settings, from the environment or a local .env file.
// Only public values go in: the Supabase URL and anon key. Never the service-role key.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

function readDotEnv(file) {
  try {
    return Object.fromEntries(fs.readFileSync(file, 'utf8').split('\n')
      .map((l) => l.trim())
      .filter((l) => l && !l.startsWith('#') && l.includes('='))
      .map((l) => { const i = l.indexOf('='); return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, '')]; }));
  } catch {
    return {};
  }
}

const env = { ...readDotEnv(path.join(root, '.env')), ...process.env };
const cfg = { supabaseUrl: env.SUPABASE_URL || '', supabaseAnonKey: env.SUPABASE_ANON_KEY || '' };
fs.writeFileSync(path.join(root, 'config.js'),
  `// Generated by scripts/write-config.js. Public values only.\nwindow.TAKEOVER_CONFIG = ${JSON.stringify(cfg)};\n`);
console.log(`config.js written ${cfg.supabaseUrl ? '(accounts enabled)' : '(no Supabase settings: accounts disabled)'}`);
